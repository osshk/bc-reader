import assert from "node:assert/strict";
import { describe, it } from "node:test";
import { formatPhone } from "@/lib/phone";

describe("formatPhone", () => {
  const cases: [string, string, string?][] = [
    ["852 2836 3295", "+852 2836 3295"],
    ["8522836-3295", "+852 2836 3295"],
    ["852-2836-3295", "+852 2836 3295"],
    ["(852)2836 3295", "+852 2836 3295"],
    ["(852) 9676-7716", "+852 9676 7716"],
    ["+852 2836 3295", "+852 2836 3295"],
    ["+(852) 2836 3295", "+852 2836 3295"],
    ["00852 2836 3295", "+852 2836 3295"],
    ["9676 7716", "+852 9676 7716"],
    ["2836-3295", "+852 2836 3295"],
    ["86 138 0013 8000", "+86 138 0013 8000"],
    ["+86 21 6888 8888", "+86 21 6888 8888"],
    ["(021) 6888 8888", "+86 21 6888 8888", "CN"],
    ["+1 415 555 0148", "+1 415 555 0148"],
    ["415-555-0148", "+1 415 555 0148", "US"],
    ["+44 20 7946 0991", "+44 20 7946 0991"],
    ["020 7946 0991", "+44 20 7946 0991", "GB"],
    ["65 6123 4567", "+65 6123 4567"],
    ["(852)2836 3295 ext. 123", "+852 2836 3295,123"],
  ];
  for (const [input, expected, country] of cases) {
    it(`${input} -> ${expected}`, () => {
      assert.equal(formatPhone(input, (country ?? "HK") as never), expected);
    });
  }

  it("leaves unknown shapes as printed", () => {
    assert.equal(formatPhone("12 34"), "12 34");
  });
});
